-- SolarScope interaction-log -> Lua translator.
-- Recordings are not tests; this expands a compact interaction log into a
-- readable, editable Lua regression test.
--
-- Use as a module (in-sim, json already decoded):
--   local translate = require("tools.translate")
--   local lua = translate.translate(compactLog, { name = "..." })
--
-- Or on the host CLI:
--   lua tools/translate.lua path/to/interactions.json > my_test.lua

local M = {}

local function q(s)
    return '"' .. tostring(s) .. '"'
end

-- compact log: { version, seed, save, actions = { {"tap",t,id,x,y}, ... } }
function M.translate(log, opts)
    opts = opts or {}
    local name = opts.name or "generated from interaction log"
    local lines = {}
    for _, a in ipairs(log.actions or {}) do
        local kind = a[1]
        if kind == "tap" then
            local id = a[3]
            if id and id ~= "" then
                lines[#lines + 1] = "        t:findById(" .. q(id) .. "):tap()"
            else
                lines[#lines + 1] = "        t:tap(" .. a[4] .. ", " .. a[5] .. ")"
            end
        elseif kind == "drag" then
            local src, tgt = a[3], a[4]
            if src and src ~= "" and tgt and tgt ~= "" then
                lines[#lines + 1] = "        t:findById(" .. q(src) .. "):dragTo(t:findById(" .. q(tgt) .. "))"
            else
                lines[#lines + 1] = "        t:drag(" .. a[5] .. ", " .. a[6] .. ", " .. a[7] .. ", " .. a[8] .. ")"
            end
        elseif kind == "control" then
            lines[#lines + 1] = "        t:control(" .. q(a[3]) .. ")"
        end
    end

    local out = {}
    out[#out + 1] = "-- Generated by solar_scope tools/translate from an interaction log."
    out[#out + 1] = "return {"
    out[#out + 1] = "    name = " .. q(name) .. ","
    if log.seed ~= nil then
        out[#out + 1] = "    seed = " .. tostring(log.seed) .. ","
    end
    if log.save ~= nil then
        out[#out + 1] = "    fixture = { type = \"save-file\", path = " .. q(log.save) .. " },"
    end
    out[#out + 1] = "    run = function(t)"
    for _, l in ipairs(lines) do
        out[#out + 1] = l
    end
    out[#out + 1] = "        t:expectNoErrors()"
    out[#out + 1] = "    end,"
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

-- ---- minimal JSON decoder (CLI only) -------------------------------------
local function decode(str)
    local pos = 1
    local parseValue

    local function skipWs()
        local _, e = str:find("^[ \t\r\n]*", pos)
        pos = e + 1
    end

    local function parseString()
        pos = pos + 1 -- opening quote
        local buf = {}
        while true do
            local c = str:sub(pos, pos)
            if c == "" then error("unterminated string") end
            if c == '"' then pos = pos + 1; break end
            if c == "\\" then
                local n = str:sub(pos + 1, pos + 1)
                local map = { n = "\n", t = "\t", r = "\r", ['"'] = '"', ["\\"] = "\\", ["/"] = "/" }
                buf[#buf + 1] = map[n] or n
                pos = pos + 2
            else
                buf[#buf + 1] = c
                pos = pos + 1
            end
        end
        return table.concat(buf)
    end

    local function parseNumber()
        local s, e = str:find("^%-?%d+%.?%d*[eE]?[%+%-]?%d*", pos)
        local num = tonumber(str:sub(s, e))
        pos = e + 1
        return num
    end

    local function parseArray()
        pos = pos + 1
        local arr = {}
        skipWs()
        if str:sub(pos, pos) == "]" then pos = pos + 1; return arr end
        while true do
            arr[#arr + 1] = parseValue()
            skipWs()
            local c = str:sub(pos, pos)
            pos = pos + 1
            if c == "]" then break end
            if c ~= "," then error("expected , or ] at " .. pos) end
            skipWs()
        end
        return arr
    end

    local function parseObject()
        pos = pos + 1
        local obj = {}
        skipWs()
        if str:sub(pos, pos) == "}" then pos = pos + 1; return obj end
        while true do
            skipWs()
            local key = parseString()
            skipWs()
            pos = pos + 1 -- colon
            obj[key] = parseValue()
            skipWs()
            local c = str:sub(pos, pos)
            pos = pos + 1
            if c == "}" then break end
            if c ~= "," then error("expected , or } at " .. pos) end
        end
        return obj
    end

    parseValue = function()
        skipWs()
        local c = str:sub(pos, pos)
        if c == "{" then return parseObject()
        elseif c == "[" then return parseArray()
        elseif c == '"' then return parseString()
        elseif c == "t" then pos = pos + 4; return true
        elseif c == "f" then pos = pos + 5; return false
        elseif c == "n" then pos = pos + 4; return nil
        else return parseNumber() end
    end

    return parseValue()
end
M.decode = decode

-- CLI entry.
if arg and arg[0] and arg[0]:match("translate%.lua$") and arg[1] then
    local f = assert(io.open(arg[1], "r"))
    local body = f:read("*a")
    f:close()
    io.write(M.translate(decode(body), { name = arg[2] or "generated from interaction log" }))
end

return M
